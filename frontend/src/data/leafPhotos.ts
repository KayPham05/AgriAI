export function attachLeafPhotos(plants: Plant[]): Plant[] {
  return plants.map((plant) => {
    const photos = LEAF_PHOTOS.filter((photo) => photo.plantId === plant.id);
    const conditions = plant.conditions.map((condition) => {
      const photo = photos.find((item) => item.id === condition.id);
      return photo
        ? {
            ...condition,
            imageUrl: photo.imageUrl,
            shortDescription: `${condition.shortDescription} ${LEAF_PHOTO_NOTE}`,
          }
        : condition;
    });
    const additions = photos
      .filter((photo) => !conditions.some((condition) => condition.id === photo.id))
      .map((photo) => ({
        id: photo.id,
        name: photo.name,
        imageUrl: photo.imageUrl,
        isHealthy: photo.isHealthy,
        shortDescription: LEAF_PHOTO_NOTE,
      }));
    return { ...plant, conditions: [...conditions, ...additions] };
  });
}

export function attachDiseasePhotos(diseases: Disease[], plants: Plant[]): Disease[] {
  const existing = diseases.map((disease) => {
    const photo = LEAF_PHOTOS.find(
      (item) => item.id === disease.id && item.plantId === disease.plantId && !item.isHealthy,
    );
    return photo
      ? {
          ...disease,
          heroImage: photo.imageUrl,
          overview: `${disease.overview} ${LEAF_PHOTO_NOTE}`,
        }
      : disease;
  });
  const additions = LEAF_PHOTOS.filter(
    (photo) => !photo.isHealthy && !existing.some((disease) => disease.id === photo.id),
  ).flatMap((photo): Disease[] => {
    const plant = plants.find((item) => item.id === photo.plantId);
    if (!plant) return [];
    return [
      {
        id: photo.id,
        name: photo.name,
        plant: plant.name,
        plantId: plant.id,
        category: 'Chưa phân loại',
        status: 'Chưa xác minh',
        heroImage: photo.imageUrl,
        overview: LEAF_PHOTO_NOTE,
        symptoms: [],
        visualCharacteristics: [],
        causes: [],
        affectedPlants: [plant.name],
        prevention: [],
        management: [],
      },
    ];
  });
  return [...existing, ...additions];
}
